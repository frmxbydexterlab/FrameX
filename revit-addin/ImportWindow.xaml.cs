                    txtFilePath.Text = _filePath;
                    LoadAndAnalyzeFile();
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show($"Browse failed with error:\n{ex.Message}\n\nStack Trace:\n{ex.StackTrace}", "Browse Error", MessageBoxButton.OK, MessageBoxImage.Error);
            }
        }
        
        private void LoadAndAnalyzeFile()
        {
            try
            {
                byte[] fileBytes = File.ReadAllBytes(_filePath);
                string jsonContent = SecurityHelper.DecryptAndDecompress(fileBytes);
                var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
                _resultData = JsonSerializer.Deserialize<FramingResultData>(jsonContent, options);

                if (_resultData == null || _resultData.Walls == null)
                {
                    txtReport.Text = "❌ Analysis Error:\n\nFailed to deserialize the .frmx file into the LGSF structure.";
                    txtReport.Foreground = System.Windows.Media.Brushes.OrangeRed;
                    btnImport.IsEnabled = false;
                    return;
                }

                // Analyze framing components
                int totalWalls = _resultData.Walls.Count;
                int totalMembers = _resultData.Walls.Sum(w => w.Members?.Count ?? 0);
                
                var families = new HashSet<string>();
                var missingFamilies = new HashSet<string>();
                var missingKeys = new HashSet<string>();

                foreach (var wall in _resultData.Walls)
                {
                    if (wall.Members == null) continue;
                    foreach (var member in wall.Members)
                    {
                        if (!string.IsNullOrEmpty(member.RevitFamilyName) && !string.IsNullOrEmpty(member.RevitSymbolName))
                        {
                            string familyDesc = $"{member.RevitFamilyName} : {member.RevitSymbolName}";
                            families.Add(familyDesc);

                            FamilySymbol customSymbol = new FilteredElementCollector(_doc)
                                .OfClass(typeof(FamilySymbol))
                                .Cast<FamilySymbol>()
                                .FirstOrDefault(x => x.FamilyName.Equals(member.RevitFamilyName, StringComparison.OrdinalIgnoreCase) 
                                                     && x.Name.Equals(member.RevitSymbolName, StringComparison.OrdinalIgnoreCase));
                            if (customSymbol == null)
                            {
                                missingFamilies.Add(familyDesc);
                                missingKeys.Add($"{member.RevitFamilyName.ToLower()}:{member.RevitSymbolName.ToLower()}");
                            }
                        }
                    }
                }

                string report = $"✔ ANALYSIS COMPLETE\n\n" +
                                $"File: {Path.GetFileName(_filePath)}\n" +
                                $"Walls in Payload: {totalWalls}\n" +
                                $"Total Framing Members: {totalMembers}\n" +
                                $"Unique Families referenced: {families.Count}\n";

                if (missingFamilies.Count > 0)
                {
                    report += $"\n⚠ MISSING FAMILIES DETECTED ({missingFamilies.Count}):\n" +
                              $"Standard SSMA profile fallbacks will be used if imported as-is:\n" +
                              string.Join("\n", missingFamilies.Select(f => $"  • {f}")) + "\n";
                    txtReport.Foreground = System.Windows.Media.Brushes.Yellow;
                }
                else
                {
                    report += "\n✔ All custom structural families are loaded and ready in project!\n";
                    txtReport.Foreground = System.Windows.Media.Brushes.LightGreen;
                }

                txtReport.Text = report;
                btnImport.IsEnabled = true;
            }
            catch (Exception ex)
            {
                txtReport.Text = $"❌ Analysis failed with error:\n\n{ex.Message}\n\nStack Trace:\n{ex.StackTrace}";
                txtReport.Foreground = System.Windows.Media.Brushes.OrangeRed;
                btnImport.IsEnabled = false;
            }
        }
        
        private void Import_Click(object sender, RoutedEventArgs e)
        {
            if (_resultData == null) return;

            try
            {
                // Scan for missing custom families/symbols
                var missingKeys = new HashSet<string>();
                var missingFamilies = new List<string>();
                foreach (var wall in _resultData.Walls)
                {
                    if (wall.Members == null) continue;
                    foreach (var member in wall.Members)
                    {
                        if (!string.IsNullOrEmpty(member.RevitFamilyName) && !string.IsNullOrEmpty(member.RevitSymbolName))
                        {
                            FamilySymbol customSymbol = new FilteredElementCollector(_doc)
                                .OfClass(typeof(FamilySymbol))
                                .Cast<FamilySymbol>()
                                .FirstOrDefault(x => x.FamilyName.Equals(member.RevitFamilyName, StringComparison.OrdinalIgnoreCase) 
                                                     && x.Name.Equals(member.RevitSymbolName, StringComparison.OrdinalIgnoreCase));
                            if (customSymbol == null)
                            {
                                string key = $"{member.RevitFamilyName.ToLower()}:{member.RevitSymbolName.ToLower()}";
                                if (!missingKeys.Contains(key))
                                {
                                    missingKeys.Add(key);
                                    missingFamilies.Add($"{member.RevitFamilyName} : {member.RevitSymbolName}");
                                }
                            }
                        }
                    }
                }

                // If missing families exist, ask how to proceed
                bool useFallback = false;
                if (missingFamilies.Count > 0)
                {
                    MessageBoxResult res = MessageBox.Show(
                        "Some custom Revit families referenced in the file are not loaded in the active project:\n\n" +
                        string.Join("\n", missingFamilies) +
                        "\n\nWould you like to use the standard SSMA profiles as fallback? (Click No to cancel import)",
                        "Missing Revit Families",
                        MessageBoxButton.YesNo,
                        MessageBoxImage.Question
                    );

                    if (res == MessageBoxResult.Yes)
                    {
                        useFallback = true;
                    }
                    else
                    {
                        return;
                    }
                }

                if (useFallback)
                {
                    foreach (var wall in _resultData.Walls)
                    {
                        if (wall.Members == null) continue;
                        foreach (var member in wall.Members)
                        {
                            if (!string.IsNullOrEmpty(member.RevitFamilyName) && !string.IsNullOrEmpty(member.RevitSymbolName))
                            {
                                string key = $"{member.RevitFamilyName.ToLower()}:{member.RevitSymbolName.ToLower()}";
                                if (missingKeys.Contains(key))
                                {
                                    member.RevitFamilyName = null;
                                    member.RevitSymbolName = null;
                                }
                            }
                        }
                    }
                }

                // Execute the import framing generation
                using (Transaction tx = new Transaction(_doc, "Import Python LGSF Framing Payload"))
                {
                    tx.Start();

                    FailureHandlingOptions failOpt = tx.GetFailureHandlingOptions();
                    failOpt.SetFailuresPreprocessor(new WarningSwallower());
                    tx.SetFailureHandlingOptions(failOpt);

                    string configName = _resultData.Metadata?.ConfigName ?? "us_default";
                    FramingBuilder builder = new FramingBuilder(_doc, configName);
                    
                    builder.EnsureFamiliesLoaded();
                    builder.EnsureInstanceParametersExist(_uiapp.Application);

                    int wIndex = 0;
                    foreach (var wall in _resultData.Walls)
                    {
                        builder.BuildWall(wall, wIndex++);
                    }

                    tx.Commit();
                }

                // Detailed success summary
                int totalWalls = _resultData.Walls.Count;
                int totalMembers = _resultData.Walls.Sum(w => w.Members?.Count ?? 0);
                string summaryReport = $"✔ IMPORT AND BUILD SUCCESSFUL\n\n" +
                                       $"Walls processed: {totalWalls}\n" +
                                       $"Framing members instantiated in Revit model space: {totalMembers}\n" +
                                       $"Standard SSMA fallback profiles utilized: {(useFallback ? "Yes" : "No")}\n" +
                                       $"\nRevit database has been committed successfully.";

                txtReport.Text = summaryReport;
                txtReport.Foreground = System.Windows.Media.Brushes.LightGreen;
                
                btnImport.IsEnabled = false;
                btnBrowse.IsEnabled = false;
                btnCancel.Content = "Close";
            }
            catch (Exception ex)
            {
                txtReport.Text = $"❌ Generation error occurred:\n\n{ex.Message}\n\nStack Trace:\n{ex.StackTrace}";
                txtReport.Foreground = System.Windows.Media.Brushes.OrangeRed;
            }
        }

        public void Dispose()
        {
            _uiapp = null;
            _doc = null;
            _resultData = null;
        }
    }

    public class WarningSwallower : IFailuresPreprocessor
    {
        public FailureProcessingResult PreprocessFailures(FailuresAccessor failuresAccessor)
        {
            var failList = failuresAccessor.GetFailureMessages();
            foreach (var failure in failList)
            {
                if (failure.GetSeverity() == FailureSeverity.Warning)
                {
                    failuresAccessor.DeleteWarning(failure);
                }
            }
            return FailureProcessingResult.Continue;
        }
    }
